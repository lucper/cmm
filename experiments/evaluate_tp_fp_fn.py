#!/usr/bin/env python3
"""
Compares the output of a motif-pair mining algorithm against a truth set produced
by motif_network_generator.py and reports TP, FP, FN, Precision, Recall, and
F1-score.

Definitions
-------------------------------------------------------------
  TP — a standardised pair reported by the tool that also appears in the
       truth set.
  FP — a standardised pair reported by the tool that does NOT appear in
       the truth set.
  FN — a standardised pair in the truth set that was NOT reported by
       the tool.

  Precision  = TP / (TP + FP)   [what fraction of reported pairs are correct]
  Recall     = TP / (TP + FN)   [what fraction of truth pairs were found]
  F1         = 2 * P * R / (P + R)

Input file formats
-------------------------------------------------------------
Three space-separated columns:
    motif_X   motif_Y   score

Input files are read as (motif_A, motif_B) pairs. Before any comparison, every
pair is normalised to (X, Y) with X <= Y under lexicographic order (i.e.
X = min(A,B), Y = max(A,B)). This ensures that (A,B) and (B,A) are treated as the
same pair regardless of which file they come from.

The score column is preserved in verbose output but is not used for
TP/FP/FN counting.

-------------------------------------------------------------

Disclaimer: This script was generated by Claude Sonnet 4.2 under the guidance
of Lucas Peres Oliveira (lpo@cwi.nl).
"""

import argparse
import sys

# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------

def standardise(a: str, b: str) -> tuple[str, str]:
    """Return (min, max) under lexicographic order so X <= Y always holds."""
    return (a, b) if a <= b else (b, a)

def load_truth(path: str) -> set[tuple[str, str]]:
    """
    Load the truth-set file (3 columns: motif_X motif_Y score).
    Returns a set of standardised (X, Y) pairs.
    """
    pairs: set[tuple[str, str]] = set()
    with open(path) as fh:
        for lineno, line in enumerate(fh, 1):
            line = line.strip()
            if not line or line.startswith("#"):
                continue
            parts = line.split()
            if len(parts) < 2:
                print(
                    f"  [WARN] truth file line {lineno}: fewer than 2 columns — skipped.",
                    file=sys.stderr,
                )
                continue
            pairs.add(standardise(parts[0], parts[1]))
    return pairs

def load_predictions(path: str) -> list[tuple[str, str, str]]:
    """
    Load the mining-algorithm output (3 columns: motif_A motif_B score).
    Returns a list of (motif_A, motif_B, score_str) with motifs upper-cased.
    Lines with fewer than 3 columns are warned and skipped.
    """
    rows: list[tuple[str, str, str]] = []
    with open(path) as fh:
        for lineno, line in enumerate(fh, 1):
            line = line.strip()
            if not line or line.startswith("#"):
                continue
            parts = line.split()
            if len(parts) < 3:
                print(
                    f"  [WARN] prediction file line {lineno}: fewer than 3 columns — skipped.",
                    file=sys.stderr,
                )
                continue
            rows.append((parts[0], parts[1], parts[2]))
    return rows


# ---------------------------------------------------------------------------
# Evaluation
# ---------------------------------------------------------------------------

def evaluate(
    truth: set[tuple[str, str]],
    predictions: list[tuple[str, str, str]],
) -> dict:
    """
    Compare standardised predicted pairs against the truth set.

    Returns a dict with:
        tp_pairs, fp_pairs  — sets of standardised (X, Y) tuples
        fn_pairs            — set of standardised (X, Y) tuples
        tp, fp, fn          — integer counts
        precision, recall, f1  — floats (None when denominator is zero)
        annotated_rows      — list of dicts for verbose output, one per
                              predicted line, with 'status' in {TP, FP, DUP}
    """
    seen: set[tuple[str, str]] = set()   # track duplicates within predictions
    tp_pairs: set[tuple[str, str]] = set()
    fp_pairs: set[tuple[str, str]] = set()
    annotated_rows: list[dict] = []

    for motif_a, motif_b, score in predictions:
        key = standardise(motif_a, motif_b)
        if key in seen:
            status = "DUP"   # duplicate prediction — not counted as new TP or FP
        elif key in truth:
            status = "TP"
            tp_pairs.add(key)
            seen.add(key)
        else:
            status = "FP"
            fp_pairs.add(key)
            seen.add(key)
        annotated_rows.append({
            "motif_a": motif_a,
            "motif_b": motif_b,
            "score":   score,
            "key":     key,
            "status":  status,
        })

    fn_pairs = truth - tp_pairs

    tp = len(tp_pairs)
    fp = len(fp_pairs)
    fn = len(fn_pairs)

    precision = tp / (tp + fp) if (tp + fp) > 0 else None
    recall    = tp / (tp + fn) if (tp + fn) > 0 else None

    if precision is not None and recall is not None and (precision + recall) > 0:
        f1 = 2 * precision * recall / (precision + recall)
    else:
        f1 = None

    return {
        "tp_pairs": tp_pairs,
        "fp_pairs": fp_pairs,
        "fn_pairs": fn_pairs,
        "tp": tp, "fp": fp, "fn": fn,
        "precision": precision,
        "recall":    recall,
        "f1":        f1,
        "annotated_rows": annotated_rows,
    }


# ---------------------------------------------------------------------------
# Reporting
# ---------------------------------------------------------------------------

STATUS_SYMBOL = {"TP": "✓", "FP": "✗", "DUP": "↺"}

def fmt_metric(value) -> str:
    return f"{value:.4f}" if value is not None else "  N/A "

def print_report(results: dict, verbose: bool) -> None:
    sep = "=" * 56

    if verbose:
        col_w = max(
            max((len(r["motif_a"]) for r in results["annotated_rows"]), default=8),
            max((len(r["motif_b"]) for r in results["annotated_rows"]), default=8),
            8,
        )
        print(f"\n── Per-prediction breakdown {'─' * 27}")
        header = (
            f"  {'Motif A':<{col_w}}  {'Motif B':<{col_w}}  "
            f"{'Score':>12}  Status"
        )
        print(header)
        print("  " + "─" * (len(header) - 2))
        for row in results["annotated_rows"]:
            sym = STATUS_SYMBOL.get(row["status"], "?")
            print(
                f"  {row['motif_a']:<{col_w}}  {row['motif_b']:<{col_w}}  "
                f"{row['score']:>12}  {sym} {row['status']}"
            )

        if results["tp_pairs"]:
            print(f"\n── True Positives ({'─' * 36}")
            for x, y in sorted(results["tp_pairs"]):
                print(f"  ✓  {x}  {y}")

        if results["fp_pairs"]:
            print(f"\n── False Positives ({'─' * 35}")
            for x, y in sorted(results["fp_pairs"]):
                print(f"  ✗  {x}  {y}")

        if results["fn_pairs"]:
            print(f"\n── False Negatives (truth pairs not reported) {'─' * 9}")
            for x, y in sorted(results["fn_pairs"]):
                print(f"  ?  {x}  {y}")

    print(f"\n{sep}")
    print("  MOTIF PAIR EVALUATION REPORT")
    print(sep)
    print(f"  {'True  Positives (TP)':<32}: {results['tp']:>6}")
    print(f"  {'False Positives (FP)':<32}: {results['fp']:>6}")
    print(f"  {'False Negatives (FN)':<32}: {results['fn']:>6}")
    print(f"  {'─' * 40}")
    print(f"  {'Precision  = TP / (TP+FP)':<32}: {fmt_metric(results['precision'])}")
    print(f"  {'Recall     = TP / (TP+FN)':<32}: {fmt_metric(results['recall'])}")
    print(f"  {'F1-score   = 2·P·R / (P+R)':<32}: {fmt_metric(results['f1'])}")
    print(sep + "\n")


# ---------------------------------------------------------------------------
# CLI
# ---------------------------------------------------------------------------

def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description=(
            "Evaluate motif-pair mining output against a truth set. "
            "Pairs are standardised to (X,Y) with X<=Y (lex) before comparison."
        ),
        formatter_class=argparse.ArgumentDefaultsHelpFormatter,
    )
    parser.add_argument(
        "--truth", required=True,
        help="Truth-set file produced by motif_network_generator.py "
             "(3 columns: motif_X motif_Y f_score)",
    )
    parser.add_argument(
        "--predicted", required=True,
        help="Mining-algorithm output (3 columns: motif_A motif_B score)",
    )
    parser.add_argument(
        "--verbose", action="store_true",
        help="Print per-prediction breakdown and TP/FP/FN pair lists",
    )
    return parser.parse_args()

def main() -> None:
    args = parse_args()

    print(f"[1/3] Loading truth set   : {args.truth}")
    truth = load_truth(args.truth)
    print(f"      {len(truth)} pair(s) loaded.")

    print(f"[2/3] Loading predictions : {args.predicted}")
    predictions = load_predictions(args.predicted)
    print(f"      {len(predictions)} row(s) loaded.")

    print("[3/3] Evaluating...")
    results = evaluate(truth, predictions)

    dups = sum(1 for r in results["annotated_rows"] if r["status"] == "DUP")
    if dups:
        print(f"      NOTE: {dups} duplicate prediction row(s) detected and ignored.")

    print_report(results, verbose=args.verbose)

if __name__ == "__main__":
    main()
