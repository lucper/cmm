#!/usr/bin/env python3
"""
Generates a synthetic protein interaction dataset with implanted (l,d)-motifs.

Disclaimer: This script was generated by Claude Sonnet 4.2 under the guidance
of Lucas Peres Oliveira (lpo@cwi.nl).
"""

import argparse
import random
from pathlib import Path
from itertools import combinations

AA_ALPHABET = list("ACDEFGHIKLMNPQRSTVWY")
WILDCARD = "x"

# ---------------------------------------------------------------------------
# I/O helpers
# ---------------------------------------------------------------------------

def read_fasta(path: str) -> dict[str, str]:
    """Return OrderedDict {id: sequence} from a FASTA file."""
    sequences: dict[str, str] = {}
    current_id = None
    buf: list[str] = []
    with open(path) as fh:
        for line in fh:
            line = line.rstrip()
            if line.startswith(">"):
                if current_id is not None:
                    sequences[current_id] = "".join(buf)
                # Use the first word (before a space) in the header as ID
                current_id = line[1:].split()[0]
                buf = []
            else:
                buf.append(line.upper())
    if current_id is not None:
        sequences[current_id] = "".join(buf)
    return sequences

def write_fasta(path: str, sequences: dict[str, str]) -> None:
    with open(path, "w") as fh:
        for sid, seq in sequences.items():
            fh.write(f">{sid}\n")
            for i in range(0, len(seq), 60):
                fh.write(seq[i:i+60] + "\n")

def read_interactions(path: str) -> list[tuple[str, str]]:
    """Return list of (id1, id2) pairs from a space-separated file."""
    edges: list[tuple[str, str]] = []
    with open(path) as fh:
        for line in fh:
            parts = line.strip().split()
            if len(parts) == 2:
                edges.append((parts[0], parts[1]))
            else:
                raise ValueError(f"Illegal line in {path}: {line.strip()}")
    return edges

def write_interactions(path: str, edges: set[tuple[str, str]]) -> None:
    with open(path, "w") as fh:
        for u, v in sorted(edges):
            fh.write(f"{u} {v}\n")

def write_motif_pairs(path: str, pairs: list[tuple[str, str, float]]) -> None:
    """Write motif pairs file: motif_X  motif_Y  f(X,Y) — space-separated."""
    with open(path, "w") as fh:
        for mx, my, score in pairs:
            fh.write(f"{mx} {my} {score:.3f}\n")


# ---------------------------------------------------------------------------
# (l,d)-motif helpers
# ---------------------------------------------------------------------------

def generate_random_motif(l: int, d: int) -> str:
    """
    Generate one random (l,d)-motif: length l, exactly d wildcard positions.
    Non-wildcard positions are sampled from AA_ALPHABET.
    """
    if d > l:
        raise ValueError(f"d={d} cannot exceed l={l}")
    positions = list(range(l))
    wildcard_positions = set(random.sample(positions, d))
    return "".join(
        WILDCARD if i in wildcard_positions else random.choice(AA_ALPHABET)
        for i in range(l)
    )

def motif_matches(motif: str, text: str, start: int) -> bool:
    """Check whether `motif` matches `text` starting at `start`."""
    for i, ch in enumerate(motif):
        if ch != WILDCARD and text[start + i] != ch:
            return False
    return True

def find_motif_positions(motif: str, sequence: str) -> list[int]:
    """Return all start positions where `motif` matches `sequence`."""
    l = len(motif)
    return [i for i in range(len(sequence) - l + 1) if motif_matches(motif, sequence, i)]

def sequence_contains_motif(motif: str, sequence: str) -> bool:
    return bool(find_motif_positions(motif, sequence))

def implant_motif(sequence: str, motif: str) -> str:
    """
    Implant `motif` at a random valid position in `sequence`.
    Wildcard positions keep the original amino acid; fixed positions are overwritten.
    Raises ValueError if the sequence is shorter than the motif.
    """
    l = len(motif)
    if len(sequence) < l:
        raise ValueError(f"Sequence shorter ({len(sequence)}) than motif length ({l}).")
    start = random.randint(0, len(sequence) - l)
    seq_list = list(sequence)
    for i, ch in enumerate(motif):
        if ch != WILDCARD:
            seq_list[start + i] = ch
    return "".join(seq_list)


# ---------------------------------------------------------------------------
# Support function helper
# ---------------------------------------------------------------------------

def edge_density(edges: set[tuple[str, str]], n: int) -> float:
    """Fraction of possible undirected edges that are present (max = n*(n-1)/2)."""
    max_edges = n * (n - 1) / 2
    if max_edges == 0:
        return 0.0
    return len(edges) / max_edges

def compute_f(
    e: int,
    density: float,
    hosts_x: set[str],
    hosts_y: set[str],
) -> float:
    """
    Compute f(X,Y) = (e - e')^2 / e'

    where:
        e'  = density * expected_interactions(X, Y)
        expected_interactions(X, Y) = k_X*k_Y - C(k_XY, 2) - k_XY
        k_X   = |hosts_X|
        k_Y   = |hosts_Y|
        k_XY  = |hosts_X ∩ hosts_Y|
        C(k_XY, 2) = k_XY*(k_XY-1)/2

    Returns 0.0 when e' == 0 (undefined) or when both e <= e'.
    """
    k_x  = len(hosts_x)
    k_y  = len(hosts_y)
    k_xy = len(hosts_x & hosts_y)

    expected = k_x * k_y - (k_xy * (k_xy - 1) // 2) - k_xy
    e_prime  = density * expected

    if e_prime == 0.0 or e <= e_prime:
        return 0.0
    return (e - e_prime) ** 2 / e_prime


# ---------------------------------------------------------------------------
# Core pipeline
# ---------------------------------------------------------------------------

def run(
    fasta_path: str,
    interactions_path: str,
    l: int,
    d: int,
    K: int,
    S: int,
    E: float,
    seed: int | None,
    out_fasta: str,
    out_interactions: str,
    out_pairs: str,
) -> None:

    if seed is not None:
        random.seed(seed)

    # -- Load inputs -------------------------------------------------------
    print("[1/7] Reading inputs...", file=sys.stderr)
    all_seqs = read_fasta(fasta_path)
    all_edges_raw = read_interactions(interactions_path)
    all_ids = list(all_seqs.keys())

    if len(all_ids) < S:
        raise SystemExit(f"FASTA contains only {len(all_ids)} sequences but S={S} was requested.")

    # -- Sample S sequences ------------------------------------------------
    print(f"[2/7] Sampling S={S} sequences...", file=sys.stderr)
    chosen_ids = random.sample(all_ids, S)
    chosen_set = set(chosen_ids)
    sequences: dict[str, str] = {sid: all_seqs[sid] for sid in chosen_ids}

    # Subset interactions to chosen proteins
    original_edges: set[tuple[str, str]] = set()
    for u, v in all_edges_raw:
        if u in chosen_set and v in chosen_set:
            a, b = (u, v) if u <= v else (v, u)
            original_edges.add((a, b))

    # -- Generate exactly K random (l,d)-motifs ----------------------------
    print(f"[3/7] Generating K={K} (l={l},d={d})-motifs...", file=sys.stderr)
    candidate_motifs: list[str] = []
    attempts = 0
    while len(candidate_motifs) < K:
        attempts += 1
        if attempts > K * 100:
            raise SystemExit(f"Could not generate {K} distinct motifs — try smaller K or larger l.")
        m = generate_random_motif(l, d)
        if m not in candidate_motifs:
            candidate_motifs.append(m)

    # -- Implant instances of all K motifs into sequences ------------------
    minI, maxI = int(0.02 * S), int(0.1 * S)
    print(f"[4/7] Implanting motif instances (I ∈ [{minI},{maxI}] per motif)...", file=sys.stderr)
    # motif_hosts[motif_idx] = set of protein IDs that contain that motif
    motif_hosts: dict[int, set[str]] = {i: set() for i in range(K)}

    # Ensure that each protein gets at least one motif
    shuffled_ids = chosen_ids[:]
    random.shuffle(shuffled_ids)
    for protein_pos, sid in enumerate(shuffled_ids):
        motif_idx = protein_pos % K
        motif_hosts[motif_idx].add(sid)

    for motif_idx in range(K):
        I = random.randint(minI, maxI)
        current = motif_hosts[motif_idx]
        if len(current) < I:
            pool = sorted([sid for sid in chosen_ids if sid not in current])
            extra = random.sample(pool, min(I - len(current), len(pool)))
            current.update(extra)

    for motif_idx, motif in enumerate(candidate_motifs):
        for sid in sorted(motif_hosts[motif_idx]):
            sequences[sid] = implant_motif(sequences[sid], motif)

    # -- Build a "perfect" network by pairing motifs until density ≥ E ----
    print(f"[5/7] Building perfect interaction network (target density E={E})...", file=sys.stderr)
    implanted_edges: set[tuple[str, str]] = set()

    # All possible motif pairs
    motif_indices = list(range(len(candidate_motifs)))
    all_motif_pairs = list(combinations(motif_indices, 2))
    random.shuffle(all_motif_pairs)

    used_motif_pairs: list[tuple[int, int]] = []

    for mx, my in all_motif_pairs:
        hosts_x = motif_hosts[mx]
        hosts_y = motif_hosts[my]
        # Add edges between all proteins containing X and all containing Y
        for u in hosts_x:
            for v in hosts_y:
                if u != v:
                    a, b = (u, v) if u <= v else (v, u)
                    implanted_edges.add((a, b))
        used_motif_pairs.append((mx, my))
        current_density = edge_density(implanted_edges, S)
        if current_density >= E:
            print(
                f"    Density {current_density:.4f} reached after "
                f"{len(used_motif_pairs)} motif pair(s).",
                file=sys.stderr
            )
            break
    else:
        current_density = edge_density(implanted_edges, S)
        print(
            f"    WARNING: All motif pairs exhausted. "
            f"Final density = {current_density:.4f} (target was {E}).",
            file=sys.stderr
        )

    # -- "Perfect" network: interactions ↔ motif-pair presence -------------
    # The implanted_edges IS the perfect network.  We discard all original
    # edges and replace them entirely so the result is perfectly explained
    # by the implanted motif pairs.
    final_edges = implanted_edges

    # -- Verify motifs actually present ------------------------------------
    # After ALL implantations are done, confirm each motif is still detectable.
    # (Earlier implants can be overwritten by later ones at overlapping sites,
    # so we re-implant any that went missing before verifying.)
    print("[6/7] Verifying / re-implanting any overwritten motifs...", file=sys.stderr)
    repaired = 0
    active_motif_indices = list(set(i for pair in used_motif_pairs for i in pair))

    # Repair pass: iterate motif-by-motif and protein-by-protein.
    # To avoid circular overwrite (motif A repairs then motif B overwrites A),
    # we collect ALL (motif, protein) slots that are missing and implant them
    # in a single sequential sweep, checking after each implant.
    missing_slots = [
        (motif_idx, sid)
        for motif_idx in active_motif_indices
        for sid in motif_hosts[motif_idx]
        if not sequence_contains_motif(candidate_motifs[motif_idx], sequences[sid])
    ]

    MAX_REPAIR_ROUNDS = 10
    for _ in range(MAX_REPAIR_ROUNDS):
        if not missing_slots:
            break
        for motif_idx, sid in missing_slots:
            sequences[sid] = implant_motif(sequences[sid], candidate_motifs[motif_idx])
            repaired += 1
        # Recompute missing after this round
        missing_slots = [
            (motif_idx, sid)
            for motif_idx in active_motif_indices
            for sid in motif_hosts[motif_idx]
            if not sequence_contains_motif(candidate_motifs[motif_idx], sequences[sid])
        ]

    # Final check
    mismatches = sum(
        1
        for motif_idx in active_motif_indices
        for sid in motif_hosts[motif_idx]
        if not sequence_contains_motif(candidate_motifs[motif_idx], sequences[sid])
    )

    if repaired:
        print(f"    Re-implanted {repaired} overwritten instance(s).", file=sys.stderr)
    if mismatches:
        print(f"    WARNING: {mismatches} motif instance(s) still missing after repair!", file=sys.stderr)
    else:
        print("    All motif instances verified ✓", file=sys.stderr)

    # -- Compute f(X,Y) for each used motif pair ---------------------------
    final_density = edge_density(final_edges, S)
    output_pairs: list[tuple[str, str, float]] = []

    for mx, my in used_motif_pairs:
        motif_x = candidate_motifs[mx]
        motif_y = candidate_motifs[my]
        hosts_x = motif_hosts[mx]
        hosts_y = motif_hosts[my]

        # Count edges in final network where one endpoint has X and other has Y
        e = sum(
            1
            for u, v in final_edges
            if (u in hosts_x and v in hosts_y) or (u in hosts_y and v in hosts_x)
        )

        score = compute_f(e, final_density, hosts_x, hosts_y)
        output_pairs.append((motif_x, motif_y, score))

    # -- Write outputs -----------------------------------------------------
    print("[7/7] Writing outputs...", file=sys.stderr)
    write_fasta(out_fasta, sequences)
    write_interactions(out_interactions, final_edges)
    write_motif_pairs(out_pairs, output_pairs)

    # -- Summary -----------------------------------------------------------
    print("\n=== Summary ===", file=sys.stderr)
    print(f"  Output FASTA          : {out_fasta}  ({S} sequences)", file=sys.stderr)
    print(f"  Output interactions   : {out_interactions}  ({len(final_edges)} edges)", file=sys.stderr)
    print(f"  Output motif pairs    : {out_pairs}  ({len(output_pairs)} pairs)", file=sys.stderr)
    print(f"  Final edge density    : {final_density:.4f}", file=sys.stderr)
    print(f"  Motif pairs used      : {len(used_motif_pairs)}", file=sys.stderr)
    print(f"  (l, d)                : ({l}, {d})", file=sys.stderr)
    print(f"  K (motifs generated)  : {K}", file=sys.stderr)
    print(f"  S (proteins)          : {S}", file=sys.stderr)
    print(f"  E (density target)    : {E}", file=sys.stderr)


# ---------------------------------------------------------------------------
# CLI
